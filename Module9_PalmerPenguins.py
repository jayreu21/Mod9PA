import math
from penguin import Penguin

# constants for penguin species and their counts
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"

NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# instructor-provided function
# returns a string read from a row of a CSV file
def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row
    with open("PalmerPenguins.csv", "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row

# returns the count as a percentage of the total
def calculate_percentage(count, total):
    return count / total * 100

# returns whether a percentage is "small", "medium", or "large"
def classify_species(percent):
    if percent < 25:
        return "small"
    elif (percent >= 25) and (percent < 40):
        return "medium"
    else:
        return "large"

# returns whether a species is the "largest", "smallest", or "middle-sized"
def get_position_description(selected_species, largest_species, smallest_species):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle-sized"

# print each species with its count and percentage
def display_species_statistics(names, counts, percentages):
    for index, species in enumerate(names):
        print(f"{species}: {counts[index]} ({percentages[index]:.2f}%)")

# print a sample penguin observation
def display_penguin_observation(sample_number, species, bill_length, bill_depth,
                                body_mass, sex):
    print("Sample Penguin Observation")
    print(f"{'Sample Number:':16}{sample_number:<}")
    print(f"{'Species:':16}{species:<}")
    print(f"{'Bill length:':16}{bill_length:<} mm")
    print(f"{'Bill depth:':16}{bill_depth:<} mm")
    print(f"{'Body mass:':16}{body_mass:<} g")
    print(f"{'Sex:':16}{sex:<}")
    print()

# run the Palmer Penguins analysis
def main():
    # create species lists
    species_names = [
        SP_CHINSTRAP,
        SP_GENTOO,
        SP_ADELIE
    ]
    species_counts = [
        NUM_CHINSTRAP,
        NUM_GENTOO,
        NUM_ADELIE
    ]

    # calculate species statistics
    total_species = len(species_names)
    total_penguins = sum(species_counts)

    average_penguins = total_penguins / total_species
    average_penguins_rounded_up = math.ceil(average_penguins)

    chinstrap_percent = calculate_percentage(species_counts[0], total_penguins)
    gentoo_percent = calculate_percentage(species_counts[1], total_penguins)
    adelie_percent = calculate_percentage(species_counts[2], total_penguins)
    species_percentages = [
        chinstrap_percent,
        gentoo_percent,
        adelie_percent
    ]

    largest_count = max(species_counts)
    smallest_count = min(species_counts)

    largest_index = species_counts.index(largest_count)
    smallest_index = species_counts.index(smallest_count)

    largest_species = species_names[largest_index]
    smallest_species = species_names[smallest_index]

    # display species statistics
    print("Introducing the Palmer Penguins:")
    print(f"\t{SP_CHINSTRAP}!")
    print(f"\t{SP_GENTOO}!")
    print("and last but not least...")
    print(f"\t{SP_ADELIE}!")
    print()

    print(f"There are a total of {total_species} penguin species in this dataset.")
    print(f"There are a total of {total_penguins} penguins in this dataset.")
    print(f"The average number of penguins per species is {average_penguins:.1f}.")
    print(f"The average rounded up is {average_penguins_rounded_up} penguins.")
    print()

    display_species_statistics(species_names, species_counts, species_percentages)
    print()

    print(f"The species with the most observations is {largest_species} with "
        f"{largest_count} penguins.")
    print(f"The species with the fewest observations is {smallest_species} with"
        f" {smallest_count} penguins.")
    print()
    print()

    # retrieve and split a CSV row
    penguin_row = read_penguin_row(1)
    penguin_data = penguin_row.split(",")

    # extract and convert values from row
    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    bill_length = float(penguin_data[2])
    bill_depth = float(penguin_data[3])
    body_mass = int(penguin_data[5])
    sex = penguin_data[6]

    # display the observation
    display_penguin_observation(sample_number, species, bill_length, bill_depth,
                                body_mass, sex)

    # retrieve and split another CSV row
    penguin_row = read_penguin_row(152)
    penguin_data = penguin_row.split(",")

    # extract and convert values from row
    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    bill_length = float(penguin_data[2])
    bill_depth = float(penguin_data[3])
    body_mass = int(penguin_data[5])
    sex = penguin_data[6]

    # display the observation
    display_penguin_observation(sample_number, species, bill_length, bill_depth,
                                body_mass, sex)

    # create a sample list of rows to be analyzed
    sample_rows = [1, 2, 3, 4, 5]
    body_masses = []

    # retrieve and split CSV rows for each sample in list
    for row in sample_rows:
        penguin_row = read_penguin_row(row)
        penguin_data = penguin_row.split(",")

        # convert and append body mass value to list
        body_mass = int(penguin_data[5])
        body_masses.append(body_mass)

    # display body masses list
    print("\nSample Body Masses")
    print(body_masses)
    print()

    # calculate body masses statistics
    body_masses_count = len(body_masses)
    body_masses_sum = sum(body_masses)
    body_masses_min = min(body_masses)
    body_masses_max = max(body_masses)
    body_masses_avg = body_masses_sum / body_masses_count

    # display body masses statistics
    print("Body Mass Summary")
    print(f"{'Observations:':20}{body_masses_count:<}")
    print(f"{'Total body mass:':20}{body_masses_sum:<} g")
    print(f"{'Smallest body mass:':20}{body_masses_min:<} g")
    print(f"{'Largest body mass:':20}{body_masses_max:<} g")
    print(f"{'Average body mass:':20}{body_masses_avg:<.2f} g")
    print()

    # create species dictionary
    species_dictionary = {
        SP_CHINSTRAP: NUM_CHINSTRAP,
        SP_GENTOO: NUM_GENTOO,
        SP_ADELIE: NUM_ADELIE
    }

    # display species counts from species dictionary
    print("Species Counts Using a Dictionary")
    for specie in species_dictionary:
        count = species_dictionary[specie]
        print(f"{specie}: {count:<}")
    print()

    # retrieve and split a previous CSV row for sample penguin object
    penguin_row = read_penguin_row(1)
    penguin_data = penguin_row.split(",")

    # create a sample penguin object from converted CSV row data
    sample_penguin = Penguin(int(penguin_data[0]), penguin_data[1],
                             int(penguin_data[5]))

    # display the sample penguin objects information using the objects function
    print("\nPenguin Object Demonstration")
    sample_penguin.display_info()

    # create a list of penguin objects from the sample rows list
    penguin_objects = []
    for row in sample_rows:
        # retrieve and split the CSV row
        penguin_row = read_penguin_row(row)
        penguin_data = penguin_row.split(",")

        # create and append a Penguin object from converted CSV row data
        penguin = Penguin(int(penguin_data[0]), penguin_data[1],
                          int(penguin_data[5]))
        penguin_objects.append(penguin)

    # display the list of penguin objects
    print("\nPenguin Objects")
    for penguin in penguin_objects:
        penguin.display_info()

    # calculate the total and average body mass of penguin objects
    total_object_mass = 0
    for penguin in penguin_objects:
        total_object_mass += penguin.body_mass
    average_object_mass = total_object_mass / len(penguin_objects)

    # display the body mass summary
    print("\nObject-Based Body Mass Summary")
    print(f"Observations: {len(penguin_objects)}")
    print(f"Total body mass: {total_object_mass} g")
    print(f"Average body mass: {average_object_mass:.2f} g")

    # request input to explore a species
    print("\nExplore a species:")
    species_choice = input(f"Enter {SP_CHINSTRAP}, {SP_GENTOO}, {SP_ADELIE}, "
                        "or Done: ")
    print()

    # validate inputted species using a while loop
    valid_selections = 0
    while species_choice != "Done":
        # reject invalid species names
        if species_choice not in species_names:
            print(f"{species_choice} is not one of the species in this dataset.")
            print()
        else:
            # count valid species and map it to its list index
            valid_selections += 1
            if species_choice == species_names[0]:
                selected_index = 0
            elif species_choice == species_names[1]:
                selected_index = 1
            else:
                selected_index = 2

            # calculate selected species statistics
            selected_species = species_names[selected_index]
            selected_count = species_counts[selected_index]
            selected_percent = species_percentages[selected_index]

            size_category = classify_species(selected_percent)
            position_description = get_position_description(selected_species, \
                                                            largest_species, \
                                                            smallest_species)
            average_position = "above" if (selected_count > average_penguins) \
                            else "below"

            # display selected species statistics
            print(f"{selected_species} has {selected_count} observations, "
                f"representing {selected_percent:.2f}% of the dataset.")
            print(f"{selected_species} is classified as a {size_category} "
                "species group.")
            print(f"{selected_species} is the {position_description} species "
                "group.")
            print(f"Its observation count is {average_position} the dataset "
                f"average of {average_penguins:.1f}")
            print()

        # request input again
        species_choice = input(f"Enter {SP_CHINSTRAP}, {SP_GENTOO}, {SP_ADELIE},"
                                " or Done: ")
        print()

    # display exploration summary
    print(f"You explored {valid_selections} valid species.")
    print("Exploration complete.")

if __name__ == "__main__":
    main()

